// Seed the LOCAL stack for the Cinema M1 recipe. Idempotent. Never touches a cloud project.
//
//   node tools/cinema-local/seed.mjs [--media-dir DIR]
//
// - writes the git-ignored .env.local from `supabase status` (keys are never printed);
// - creates two local admin accounts (cinema-a@example.test, cinema-b@example.test) with random passwords;
// - gives account A the "premium" plan locally so the daily job quota of the free plan does not hide the real gate;
// - loads five finished H3 runs (four for A, one for B) with their Corrected (final) and Original (raw) MP4 and a
//   private first-frame image per account. Clips are synthetic H.264/AAC clips shaped like H3 output (480x832,
//   24 fps, 124 frames, AAC-LC 32 kHz stereo) unless --media-dir provides plan1.mp4, plan2.mp4, plan2_old.mp4 and
//   plan3.mp4 (Corrected audio; <name>_raw.mp4 optional). Test media is never committed.
//
// The H3 gate is NOT touched here: the recipe configures it itself, in the local database only.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { randomBytes, randomUUID } from "node:crypto";
import path from "node:path";
import { ROOT, serviceClient, ffmpegPath, psql, hex, assertLocal } from "./lib.mjs";

const mediaDirArg = process.argv.indexOf("--media-dir");
const MEDIA = mediaDirArg > 0 ? path.resolve(process.argv[mediaDirArg + 1]) : null;
const OUT = path.join(ROOT, "tmp/cinema-local/media");
mkdirSync(OUT, { recursive: true });
const ENV_FILE = path.join(ROOT, ".env.local");

// ---- 1. .env.local --------------------------------------------------------------------------------------------
const readEnv = () => existsSync(ENV_FILE) ? Object.fromEntries(readFileSync(ENV_FILE, "utf8").split(/\r?\n/).filter((l) => l && !l.startsWith("#") && l.includes("=")).map((l) => { const i = l.indexOf("="); return [l.slice(0, i), l.slice(i + 1)]; })) : {};
let env = readEnv();
if (!env.SUPABASE_SERVICE_ROLE_KEY || !env.NEXT_PUBLIC_SUPABASE_URL) {
  const r = spawnSync("npx", ["--yes", "supabase@3.2.0", "status", "-o", "env"], { cwd: ROOT, encoding: "utf8", shell: process.platform === "win32" });
  if (r.status !== 0) throw new Error("`supabase status` failed: is the local stack running? (npx supabase@3.2.0 start ...)");
  const s = Object.fromEntries(String(r.stdout).split(/\r?\n/).filter((l) => l.includes("=")).map((l) => { const i = l.indexOf("="); return [l.slice(0, i), l.slice(i + 1).replace(/^"|"$/g, "")]; }));
  env = { ...env, NEXT_PUBLIC_SUPABASE_URL: s.API_URL, NEXT_PUBLIC_SUPABASE_ANON_KEY: s.ANON_KEY, SUPABASE_SERVICE_ROLE_KEY: s.SERVICE_ROLE_KEY };
}
assertLocal(env.NEXT_PUBLIC_SUPABASE_URL);
const db = serviceClient(env);

// ---- 2. accounts ----------------------------------------------------------------------------------------------
const users = { A: "cinema-a@example.test", B: "cinema-b@example.test" };
env.NEXT_PUBLIC_ADMIN_EMAILS = Object.values(users).join(",");
env.NEXT_PUBLIC_SITE_URL = "http://localhost:3000";
const existing = (await db.auth.admin.listUsers({ perPage: 200 })).data?.users ?? [];
for (const [key, email] of Object.entries(users)) {
  let u = existing.find((x) => x.email === email);
  if (!u) {
    const password = randomBytes(18).toString("base64url");
    const made = await db.auth.admin.createUser({ email, password, email_confirm: true });
    if (made.error) throw new Error("createUser " + email + ": " + made.error.message);
    u = made.data.user; env[`LOCAL_TEST_USER_${key}_PASSWORD`] = password;
  } else if (!env[`LOCAL_TEST_USER_${key}_PASSWORD`]) {
    const password = randomBytes(18).toString("base64url");
    const upd = await db.auth.admin.updateUserById(u.id, { password });
    if (upd.error) throw new Error("updateUser " + email + ": " + upd.error.message);
    env[`LOCAL_TEST_USER_${key}_PASSWORD`] = password;
  }
  env[`LOCAL_TEST_USER_${key}_ID`] = u.id; env[`LOCAL_TEST_USER_${key}_EMAIL`] = email;
}
writeFileSync(ENV_FILE, [
  "# LOCAL ONLY (git-ignored). Generated by tools/cinema-local/seed.mjs from the local Supabase stack.",
  "# Never copy these values to Vercel or production. COMFY_* variables are deliberately absent:",
  "# generation stays locked unless you start the simulated dispatcher (tools/cinema-local/dev.mjs --simulated).",
  ...Object.entries(env).map(([k, v]) => `${k}=${v}`), "",
].join("\n"), { mode: 0o600 });
const A = env.LOCAL_TEST_USER_A_ID, B = env.LOCAL_TEST_USER_B_ID;
const plan = psql(`update public.profiles set plan='premium' where id='${A}'; select count(*) from public.profiles where id='${A}' and plan='premium';`);
if (plan.stdout.split("\n").pop() !== "1") throw new Error("Could not set the local premium plan for account A: " + (plan.error || plan.stdout));
console.log("accounts ready (A premium locally, B free); env written to .env.local");

// ---- 3. media -------------------------------------------------------------------------------------------------
const ff = ffmpegPath();
const run = (args) => { const r = spawnSync(ff, ["-hide_banner", "-loglevel", "error", "-y", ...args], { encoding: "utf8" }); if (r.status !== 0) throw new Error("ffmpeg failed: " + r.stderr); };
const ENC = ["-c:v", "libx264", "-profile:v", "high", "-pix_fmt", "yuv420p", "-bf", "2", "-g", "48", "-c:a", "aac", "-b:a", "160k", "-ac", "2", "-ar", "32000"];
const synth = (file, hue, tone) => run(["-f", "lavfi", "-i", "testsrc2=size=480x832:rate=24", "-f", "lavfi", "-i", `sine=frequency=${tone}:sample_rate=32000`,
  "-vf", `hue=h=${hue}`, "-frames:v", "124", "-t", "5.1666667", ...ENC, file]);
const rawFrom = (finalFile, rawFile, tone) => run(["-i", finalFile, "-f", "lavfi", "-i", `sine=frequency=${tone}:sample_rate=32000`, "-map", "0:v:0", "-map", "1:a:0",
  "-c:v", "copy", "-c:a", "aac", "-b:a", "160k", "-ac", "2", "-ar", "32000", "-frames:v", "124", "-t", "5.1666667", rawFile]);
// Corrected (final) and Original (raw) use different tones so a test can tell which audio a montage carries.
const PLANS = [
  { key: "plan1", owner: A, id: "cd598314-0000-4000-8000-000000000001", hue: 0, final: 440, raw: 220, prompt: "Luz, full shot, push-in (local fixture plan 1)" },
  { key: "plan2_old", owner: A, id: "731316da-0000-4000-8000-000000000002", hue: 60, final: 550, raw: 275, prompt: "Luz, medium shot (local fixture, old plan 2)" },
  { key: "plan2", owner: A, id: "a1bc89fe-0000-4000-8000-000000000003", hue: 120, final: 660, raw: 330, prompt: "Luz, full shot, push-in (local fixture plan 2)" },
  { key: "plan3", owner: A, id: "e3d7a11c-0000-4000-8000-000000000004", hue: 180, final: 880, raw: 440, prompt: "Luz, wide shot (local fixture plan 3)" },
  { key: "b_plan3", owner: B, id: "b0b0b0b0-0000-4000-8000-000000000006", hue: 240, final: 990, raw: 495, prompt: "Other administrator's clip (local isolation fixture)" },
];
for (const p of PLANS) {
  p.finalFile = path.join(OUT, p.key + ".mp4"); p.rawFile = path.join(OUT, p.key + "_raw.mp4");
  const given = MEDIA && path.join(MEDIA, p.key + ".mp4");
  if (given && existsSync(given)) {
    writeFileSync(p.finalFile, readFileSync(given));
    const givenRaw = path.join(MEDIA, p.key + "_raw.mp4");
    if (existsSync(givenRaw)) writeFileSync(p.rawFile, readFileSync(givenRaw)); else rawFrom(p.finalFile, p.rawFile, p.raw);
    p.real = true;
  } else { synth(p.finalFile, p.hue, p.final); rawFrom(p.finalFile, p.rawFile, p.raw); p.real = false; }
}
// A clip whose audio is shorter than its video would shift every later clip of a montage (the montage trims, it does not pad).
// Real H3 clips are padded already; a fixture cut by hand may not be. Pad the audio up to a whole AAC packet past the video.
const stats = (f, extra) => String(spawnSync(ff, ["-hide_banner", "-stats", "-i", f, ...extra, "-f", "null", "-"], { encoding: "utf8", maxBuffer: 1 << 26 }).stderr);
// Exact length: count the decoded samples (the `time=` of the progress line is not reliable for AAC).
const audioSeconds = (f) => { const r = spawnSync(ff, ["-v", "error", "-i", f, "-vn", "-f", "f32le", "-ac", "1", "-ar", "32000", "-"], { maxBuffer: 1 << 27 }); return r.stdout.length / 4 / 32000; };
const videoSeconds = (f) => Number([...stats(f, ["-an"]).matchAll(/frame=\s*(\d+)/g)].pop()?.[1]) / 24;
function ensureAudioCoversVideo(file) {
  const v = videoSeconds(file), a = audioSeconds(file);
  if (!(a < v - 0.001)) return false;
  const target = (Math.ceil(v * 32000 / 1024) * 1024) / 32000, tmp = file + ".padded.mp4";
  run(["-i", file, "-map", "0:v:0", "-map", "0:a:0", "-c:v", "copy", "-af", `apad=whole_dur=${target.toFixed(4)}`, "-c:a", "aac", "-b:a", "160k", "-ac", "2", "-ar", "32000", tmp]);
  writeFileSync(file, readFileSync(tmp)); return true;
}
const frameFile = path.join(OUT, "first_frame.png");
run(["-i", PLANS[0].finalFile, "-frames:v", "1", frameFile]);

// ---- 4. first-frame images, runs and assets ------------------------------------------------------------------
for (const owner of [A, B]) {
  const listed = await db.storage.from("references").list(owner + "/library");
  if (!(listed.data ?? []).some((f) => f.name.startsWith(hex("Luz") + "_"))) {
    const up = await db.storage.from("references").upload(`${owner}/library/${hex("Luz")}_${randomUUID()}.png`, readFileSync(frameFile), { contentType: "image/png" });
    if (up.error) throw new Error("reference upload: " + up.error.message);
  }
}
let created = 0;
for (const p of PLANS) {
  const known = (await db.from("comfy_runs").select("id").eq("id", p.id).maybeSingle()).data;
  if (!known) {
    const job = await db.from("jobs").insert({ user_id: p.owner, prompt: p.prompt, status: "done", current_stage: "completed", engine_used: "comfy:minimax-h3",
      metadata: { output_kind: "video", template_slug: "minimax-h3", fixture: true } }).select("id").single();
    if (job.error) throw new Error("job: " + job.error.message);
    const r = await db.from("comfy_runs").insert({ id: p.id, job_id: job.data.id, user_id: p.owner, idempotency_key: randomUUID(), runtime: "h3-video@1", template_version: "minimax-h3@1",
      params_effective: { prompt: p.prompt, seconds: 5, aspect: "9:16", quality: "turbo", fixture: true }, resolved_graph_sha256: "fixture-" + p.key, status: "done",
      reserved_cost_usd: 0, finance_status: "awaiting_reconciliation", finished_at: new Date().toISOString() });
    if (r.error) throw new Error("run " + p.key + ": " + r.error.message);
    created++;
  }
  // Add whichever of the two audio variants is missing (an older seed only loaded the Corrected file).
  const have = ((await db.from("comfy_assets").select("role").eq("run_id", p.id)).data ?? []).map((a) => a.role);
  if (known && have.includes("final") && !have.includes("raw")) {
    const dl = await db.storage.from("comfy-outputs").download(`${p.owner}/${p.id}/final.mp4`);
    if (dl.error || !dl.data) throw new Error("download existing final of " + p.key);
    writeFileSync(p.finalFile, Buffer.from(await dl.data.arrayBuffer())); rawFrom(p.finalFile, p.rawFile, p.raw);
  }
  // Repair a stored Corrected clip whose audio is short (and re-derive its Original), or pad a clip about to be uploaded.
  if (have.includes("final")) {
    const dl2 = await db.storage.from("comfy-outputs").download(`${p.owner}/${p.id}/final.mp4`);
    writeFileSync(p.finalFile, Buffer.from(await dl2.data.arrayBuffer()));
  }
  if (ensureAudioCoversVideo(p.finalFile)) {
    rawFrom(p.finalFile, p.rawFile, p.raw);
    for (const [role, file] of [["final", p.finalFile], ["raw", p.rawFile]]) {
      const key = `${p.owner}/${p.id}/${role}.mp4`;
      const up = await db.storage.from("comfy-outputs").upload(key, readFileSync(file), { contentType: "video/mp4", upsert: true });
      if (up.error) throw new Error("re-upload " + key + ": " + up.error.message);
      if (!have.includes(role)) { const ins2 = await db.from("comfy_assets").insert({ run_id: p.id, owner_id: p.owner, role, storage_key: key, mime: "video/mp4" }); if (ins2.error) throw new Error("asset: " + ins2.error.message); }
    }
    console.log("padded the audio of " + p.key + " so it covers its video");
    continue;
  }
  for (const [role, file] of [["raw", p.rawFile], ["final", p.finalFile]]) {
    if (have.includes(role)) continue;
    const key = `${p.owner}/${p.id}/${role}.mp4`;
    const up = await db.storage.from("comfy-outputs").upload(key, readFileSync(file), { contentType: "video/mp4", upsert: true });
    if (up.error) throw new Error("upload " + key + ": " + up.error.message);
    const asset = await db.from("comfy_assets").insert({ run_id: p.id, owner_id: p.owner, role, storage_key: key, mime: "video/mp4" });
    if (asset.error) throw new Error("asset: " + asset.error.message);
  }
}
console.log(`fixtures ready: ${PLANS.length} runs (${created} created now), ${PLANS.some((p) => p.real) ? "real clips from --media-dir" : "synthetic H3-shaped clips"}; Corrected = final, Original = raw`);
